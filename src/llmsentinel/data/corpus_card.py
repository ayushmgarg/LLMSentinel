"""Corpus card generation.

The card is the document a reader consults before believing any number in the
report: what is in the corpus, where each part came from, under which licence,
how it was split, and what it does *not* cover.  It is generated from the corpus
itself so it cannot drift away from the data.
"""

from __future__ import annotations

from collections.abc import Sequence
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from ..schema import CorpusRecord, Split, count_by
from .loaders.base import SourceSpec
from .splits import SplitManifest

__all__ = ["render_corpus_card", "write_corpus_card"]


def _table(headers: Sequence[str], rows: Sequence[Sequence[Any]]) -> str:
    lines = ["| " + " | ".join(str(h) for h in headers) + " |"]
    lines.append("|" + "|".join("---" for _ in headers) + "|")
    for row in rows:
        lines.append("| " + " | ".join(str(cell) for cell in row) + " |")
    return "\n".join(lines)


def _pct(part: int, total: int) -> str:
    return f"{(100.0 * part / total):.1f}%" if total else "n/a"


def render_corpus_card(
    records: Sequence[CorpusRecord],
    manifest: SplitManifest,
    sources: Sequence[SourceSpec],
    *,
    skipped: Sequence[str] = (),
    warnings: Sequence[str] = (),
    extra_notes: Sequence[str] = (),
) -> str:
    total = len(records)
    positives = sum(record.y for record in records)
    hard_negatives = sum(1 for record in records if record.is_hard_negative)
    benign = total - positives

    by_split_label = count_by(records, "split", "label")
    by_channel_label = count_by(records, "channel", "label")
    by_attack = count_by(records, "attack_type")
    by_source = count_by(records, "source_dataset", "label")
    by_split_channel = count_by(records, "split", "channel")

    by_split_channel_label = count_by(records, "split", "channel", "label")

    lines: list[str] = [
        "# Corpus card",
        "",
        "Generated by the corpus build; do not edit by hand.",
        "",
    ]

    if warnings:
        lines.extend(
            [
                "> ## Read before quoting any number from this corpus",
                ">",
                *[f"> - {warning}" for warning in warnings],
                "",
            ]
        )

    lines.extend([
        f"- Generated (UTC): `{datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M:%S')}`",
        f"- Corpus digest (`data_version`): `{manifest.corpus_digest}`",
        f"- Split seed: `{manifest.seed}`",
        f"- Records: **{total}** ({positives} injection, {benign} benign)",
        f"- Hard negatives: **{hard_negatives}** = {_pct(hard_negatives, benign)} of benign "
        f"(protocol minimum: 25%)",
        f"- Records dropped to keep groups inside one split: {manifest.dropped_cross_group}",
        "",
    ])
    lines.extend([
        "## Splits",
        "",
        _table(
            ["split", "label", "records"],
            [[key[0], "injection" if key[1] == 1 else "benign", value] for key, value in by_split_label.items()],
        ),
        "",
        "## Channels",
        "",
        _table(
            ["channel", "label", "records"],
            [[key[0], "injection" if key[1] == 1 else "benign", value] for key, value in by_channel_label.items()],
        ),
        "",
        _table(
            ["split", "channel", "records"],
            [[key[0], key[1], value] for key, value in by_split_channel.items()],
        ),
        "",
        "Positives per cell decide what a per-channel number can support; a cell with",
        "no injection examples cannot be calibrated or claimed at all.",
        "",
        _table(
            ["split", "channel", "label", "records"],
            [
                [key[0], key[1], "injection" if key[2] == 1 else "benign", value]
                for key, value in by_split_channel_label.items()
            ],
        ),
        "",
        "## Attack types",
        "",
        _table(["attack_type", "records"], [[key[0], value] for key, value in by_attack.items()]),
        "",
        "## Sources",
        "",
        _table(
            ["source", "label", "records"],
            [[key[0], "injection" if key[1] == 1 else "benign", value] for key, value in by_source.items()],
        ),
        "",
    ])

    for spec in sources:
        lines.extend(
            [
                f"### {spec.name}",
                "",
                f"- Homepage: {spec.homepage}",
                f"- Licence: {spec.license}",
                f"- Citation: {spec.citation}",
                f"- Acquisition: {spec.acquisition or 'n/a'}",
                f"- Notes: {spec.notes or 'n/a'}",
                "",
            ]
        )

    if skipped:
        lines.extend(["## Sources not available in this build", ""])
        lines.extend(f"- {reason}" for reason in skipped)
        lines.append("")

    lines.extend(
        [
            "## Construction and leakage control",
            "",
            "- Every record declares a **content group** (payload template, distractor or",
            "  hard-negative identity) and a **host group** (the document or tool response it",
            "  was inserted into).",
            "- Both keys are assigned to a split from one global namespace; records whose two",
            "  keys land in different splits are dropped rather than silently reassigned.",
            "- Exact duplicates are removed before splitting; `llmsentinel corpus check` also",
            "  audits near duplicates across splits with a 5-gram Jaccard test.",
            "- Positives and negatives share the same host documents and the same insertion",
            "  positions, so document structure carries no label information.",
            "",
            "## Known limitations",
            "",
            "- The built-in seed corpus is synthetic. Its payload diversity is bounded by the",
            "  templates in `data/seed/payloads.yaml`, so results on it are optimistic relative",
            "  to an adaptive attacker.",
            "- English only. No multilingual, image or audio channel.",
            "- Multi-hop payloads assembled across several retrieved chunks are out of scope.",
            "",
        ]
    )
    lines.extend(extra_notes)
    return "\n".join(lines).rstrip() + "\n"


def write_corpus_card(
    path: str | Path,
    records: Sequence[CorpusRecord],
    manifest: SplitManifest,
    sources: Sequence[SourceSpec],
    *,
    skipped: Sequence[str] = (),
    warnings: Sequence[str] = (),
) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        render_corpus_card(records, manifest, sources, skipped=skipped, warnings=warnings),
        encoding="utf-8",
    )
    return path


def split_summary(records: Sequence[CorpusRecord]) -> dict[str, dict[str, int]]:
    """Compact counts used by the CLI and the demo's dataset panel."""

    summary: dict[str, dict[str, int]] = {}
    for split in (*Split, None):
        key = split.value if split else "unassigned"
        subset = [record for record in records if record.split is split]
        if not subset:
            continue
        summary[key] = {
            "records": len(subset),
            "injection": sum(record.y for record in subset),
            "benign": sum(1 - record.y for record in subset),
            "hard_negatives": sum(1 for record in subset if record.is_hard_negative),
        }
    return summary
